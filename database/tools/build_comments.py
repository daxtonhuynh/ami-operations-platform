#!/usr/bin/env python3
"""Generate database/04_comments.sql from the documentation written next to the DDL.

Conventions read from the source files
  01_schema.sql      "-- @table <text>" line(s) just above "create table"   -> COMMENT ON TABLE
                     "<column> <type> ... -- <text>" inside the table body  -> COMMENT ON COLUMN
                     "-- <text>" lines just above "create domain"/"create or replace function" -> COMMENT ON DOMAIN/FUNCTION
  02_functions.sql   "-- <text>" lines just above "create or replace function"   -> COMMENT ON FUNCTION
  03_views.sql       "-- <text>" lines just above "create or replace view"       -> COMMENT ON VIEW

Usage:  python3 tools/build_comments.py            (run from the database/ folder or anywhere)
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCHEMAS = {
    "ref": "Reference & master data: programmes, courses, price lists, fees, payment plans, discounts, salary codes, code tables",
    "crm": "Students (customers), guardians, leads, funnel history and placement tests (legacy: Customer Master Database)",
    "academic": "Rooms, classes, meeting patterns, sessions, staffing, attendance (legacy: Course Administration)",
    "billing": "Enrolments, pricing, payment schedules, receipts, allocations, refunds, write-offs, revenue schedule (legacy: Qualified Leads, Receipts Management)",
    "hr": "Employees, HR roles and salary codes, personal rates, fixed pay, Learning Advisor shifts (legacy: Salary Pipeline, Working Schedule)",
    "payroll": "Payroll runs, payroll lines, payslips, commissions, PIT and statutory deduction rules (legacy: Pipeline, Payroll register)",
    "finance": "Fiscal periods, chart of accounts, P&L layout, cost centres, vendors, vouchers, claims, fixed assets, journals (legacy: Payment Control, P&L)",
    "ctl": "Operational controls: control catalogue, control runs and the exception queue",
    "rpt": "Reporting views: statuses, funnel, balances, payroll register, P&L (cash and accrual), deferred revenue, KPIs",
    "app": "Application layer: users and sign-in, audit trail, daily cash close",
}
CONSTRAINT_WORDS = {"primary", "unique", "foreign", "check", "exclude", "constraint", "references", "or", "and"}
TYPE_START = re.compile(r"^(bigint|integer|smallint|int|text|date|boolean|numeric|ref\.|timestamp|time|jsonb|json|char|varchar|daterange|interval|uuid)", re.I)


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def preceding_comment(lines, i):
    """Plain '-- ' comment lines directly above line i (blank lines stop the search)."""
    out = []
    j = i - 1
    while j >= 0 and lines[j].startswith("--"):
        out.append(lines[j][2:].strip())
        j -= 1
    out.reverse()
    out = [re.sub(r"^@table\s*", "", x) for x in out]
    out = [re.sub(r"^\d+\.\s+", "", x) for x in out]          # "-- 4. Journal entries ..." -> "Journal entries ..."
    return " ".join(x for x in out if x)


def split_args(arg_text):
    depth, cur, parts = 0, "", []
    for ch in arg_text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return parts


def function_signature(source, start):
    """'billing.allocate_receipt(bigint, bigint)' from the text after 'create or replace function'."""
    m = re.match(r"\s*([a-z_]+\.[a-z_]+)\s*\(", source[start:], re.I)
    name = m.group(1)
    pos = start + m.end()
    depth, k = 1, pos
    while depth:
        if source[k] == "(":
            depth += 1
        elif source[k] == ")":
            depth -= 1
        k += 1
    args = source[pos:k - 1]
    types = []
    for a in split_args(args):
        a = re.split(r"\s+default\s+|\s*=\s*", a.strip(), flags=re.I)[0]
        toks = a.split()
        if not toks:
            continue
        if toks[0].lower() in ("in", "out", "inout", "variadic"):
            toks = toks[1:]
        types.append(" ".join(toks[1:]) if len(toks) > 1 else toks[0])
    return f"{name}({', '.join(types)})"


def main():
    out = ["/* =====================================================================================",
           "   04_comments.sql - GENERATED by tools/build_comments.py from the comments in 01-03.",
           "   Do not edit by hand: edit the comment next to the DDL and regenerate.",
           "   The comments surface in psql (\\d+), DBeaver/pgAdmin and in docs/DATA_DICTIONARY.md.",
           "   ===================================================================================== */", ""]
    counts = {"table": 0, "column": 0, "view": 0, "function": 0, "domain": 0, "schema": 0}

    schema_sql = (ROOT / "01_schema.sql").read_text(encoding="utf-8")
    lines = schema_sql.split("\n")

    for name, desc in SCHEMAS.items():
        out.append(f"comment on schema {name} is {q(desc)};")
        counts["schema"] += 1
    out.append("")

    table = None
    for i, line in enumerate(lines):
        m = re.match(r"create table ([a-z_]+\.[a-z_]+)\s*\(", line)
        if m:
            table = m.group(1)
            text = preceding_comment(lines, i)
            if text:
                out.append(f"comment on table {table} is {q(text)};")
                counts["table"] += 1
            continue
        if table and re.match(r"^\);?", line):
            table = None
            out.append("")
            continue
        if table:
            cm = re.match(r"^\s+([a-z_][a-z0-9_]*)\s+(.+?)--\s*(.+?)\s*$", line)
            if cm and cm.group(1).lower() not in CONSTRAINT_WORDS and TYPE_START.match(cm.group(2).strip()):
                out.append(f"comment on column {table}.{cm.group(1)} is {q(cm.group(3))};")
                counts["column"] += 1
            continue
        dm = re.match(r"create domain ([a-z_]+\.[a-z_]+)", line)
        if dm:
            text = re.search(r"--\s*(.+)$", line)
            if text:
                out.append(f"comment on domain {dm.group(1)} is {q(text.group(1))};")
                counts["domain"] += 1

    out.append("")
    for fname in ("01_schema.sql", "02_functions.sql"):
        src = (ROOT / fname).read_text(encoding="utf-8")
        flines = src.split("\n")
        offset = 0
        for i, line in enumerate(flines):
            if line.startswith("create or replace function"):
                text = preceding_comment(flines, i)
                if text:
                    sig = function_signature(src, offset + len("create or replace function"))
                    out.append(f"comment on function {sig} is {q(text)};")
                    counts["function"] += 1
            offset += len(line) + 1

    out.append("")
    vlines = (ROOT / "03_views.sql").read_text(encoding="utf-8").split("\n")
    for i, line in enumerate(vlines):
        m = re.match(r"create or replace view ([a-z_]+\.[a-z0-9_]+)", line)
        if m:
            text = preceding_comment(vlines, i)
            if text:
                out.append(f"comment on view {m.group(1)} is {q(text)};")
                counts["view"] += 1

    (ROOT / "04_comments.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("04_comments.sql:", ", ".join(f"{v} {k}s" for k, v in counts.items()))


if __name__ == "__main__":
    main()
