-- 1. Funnel history: record every stage a lead enters
create or replace function crm.log_lead_stage() returns trigger language plpgsql as $$
begin
    if tg_op = 'INSERT' or new.stage_code is distinct from old.stage_code then
        insert into crm.lead_stage_history (lead_id, stage_code, entered_at)
        values (new.lead_id, new.stage_code, coalesce(new.updated_at, now()));
    end if;
    return new;
end $$;
create trigger trg_lead_stage_history after insert or update of stage_code on crm.lead
    for each row execute function crm.log_lead_stage();

