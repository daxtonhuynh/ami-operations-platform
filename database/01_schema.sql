-- @table Monthly accounting periods; closing a period locks postings dated in it.
create table finance.fiscal_period (
    period_id    integer primary key,             -- YYYYMM, e.g. 202504
    period_start date not null unique,            -- First day of the month
    period_end   date not null,                   -- Last day of the month
    fiscal_year  smallint not null,               -- Fiscal year the period belongs to
    status       text not null default 'OPEN' check (status in ('OPEN','CLOSED')),  -- CLOSED periods reject new postings
    closed_at    timestamptz,                     -- When the period was closed
    check (period_start = date_trunc('month', period_start)::date),
    check (period_end = (period_start + interval '1 month - 1 day')::date),
    check (period_id = extract(year from period_start)::int * 100 + extract(month from period_start)::int)
);

-- @table Chart of accounts: revenue (I*), contra-revenue (E0), expenses (E1-E8) and the balance-sheet accounts needed for journals (B*).
create table finance.gl_account (
    account_code        text primary key,         -- e.g. I1.0011, E1.0013, E7.012, B2.001. Legacy: 'Expense Category' / 'Revenue Category'
    name                text not null,            -- Account name
    account_class       text not null             -- Statement class of the account
        check (account_class in ('REVENUE','CONTRA_REVENUE','EXPENSE','ASSET','LIABILITY','EQUITY')),
    parent_account_code text references finance.gl_account,   -- Roll-up parent (E1.0011 -> E1.001)
    is_postable         boolean not null default true,        -- Header accounts (with children) are not postable
    is_capex            boolean not null default false,       -- Purchases capitalised to fixed assets instead of expensed
    is_depreciation     boolean not null default false,       -- Depreciation/allocation charge; added back for EBITDA
    legacy_source       text,                                 -- Where the account existed in the legacy workbooks
    sort_order          integer                               -- Presentation order
);

-- @table Cost centres (departments / programmes) that every expense and payroll line is charged to.
create table finance.cost_center (
    cost_center_code    text primary key,          -- 921010 ... 921017. Legacy: 'Cost Center' sheet / CC.Code
    name                text not null,             -- Department name
    is_academic         boolean not null,          -- Academic cost centres map shared accounts to cost of sales
    programme_code      text references ref.programme,  -- Programme cost centres (COMM / AE / IELTS)
    manager_employee_id bigint,                    -- Accountable manager (FK added after hr.employee)
    is_active           boolean not null default true   -- Inactive centres cannot receive new postings
);

-- @table Lines of the management P&L (layout). Legacy line codes DC/SA/DA/EC/AC are kept for traceability.
create table finance.pnl_line (
    pnl_line_code    text primary key,             -- e.g. COS-TEACH, STF-VAR ... (stable code used by reports)
    name             text not null,                -- Line caption
    section          text not null                 -- Statement section
        check (section in ('REVENUE','REVENUE_DEDUCTIONS','COST_OF_SALES','STAFF_COSTS','MARKETING_COSTS','ESTABLISHMENT_COSTS','ADMINISTRATION_COSTS')),
    subsection       text,                         -- Sub-heading, e.g. 'Teaching cost', 'Campaign'
    legacy_line_code text,                         -- DC01, SA01, DA05 ... from the legacy P&L sheet
    sort_order       integer not null              -- Presentation order
);

-- @table Maps GL accounts to P&L lines. Accounts used by both academic and non-academic staff map by cost-centre scope.
create table finance.pnl_line_mapping (
    account_code      text not null references finance.gl_account,    -- Postable P&L account
    cost_center_scope text not null default 'ANY'                      -- ANY, or ACADEMIC / NON_ACADEMIC for shared accounts (insurance, union fee ...)
        check (cost_center_scope in ('ANY','ACADEMIC','NON_ACADEMIC')),
    pnl_line_code     text not null references finance.pnl_line,      -- Target P&L line
    primary key (account_code, cost_center_scope)
);

-- @table Revenue account for each programme and delivery mode (legacy revenue codes I1.0011 ... I1.00113).
create table finance.revenue_account_map (
    programme_code     text not null references ref.programme,        -- Programme
    delivery_mode_code text not null references ref.delivery_mode,    -- Delivery mode
    account_code       text not null references finance.gl_account,   -- Revenue account
    primary key (programme_code, delivery_mode_code)
);

