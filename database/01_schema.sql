/* =====================================================================================
   AMI Education - Integrated Operations Database
   Relational model of the Excel/SharePoint "Zero-Cost Information System"
   Target: PostgreSQL 15+   (tested on PostgreSQL 16)

   Schemas
     ref       reference & master data (programmes, courses, prices, plans, discounts, codes)
     crm       students, guardians, leads, placement tests           (legacy: Customer Master Database)
     academic  classes, meeting patterns, sessions, staffing          (legacy: Course Administration)
     billing   enrolments, pricing, payment schedules, receipts,      (legacy: Qualified Leads,
               allocations, refunds, write-offs, revenue schedule        Receipts Management)
     hr        employees, roles (HR codes), rates, shifts             (legacy: Salary Pipeline,
                                                                          Working Schedule)
     payroll   payroll runs, lines, payslips, commissions, tax rules  (legacy: Pipeline, Payroll register)
     finance   periods, chart of accounts, P&L layout, cost centres,  (legacy: Payment Control,
               vendors, vouchers, claims, fixed assets, journals         Expense Category, P&L)
     ctl       control catalogue, control runs, exception queue       (new: operational controls)
     app       application users, audit log, daily cash close         (new: access control and traceability)
     rpt       reporting views (see 03_views.sql)

   Conventions
     * surrogate keys  <entity>_id  (identity);  business keys are UNIQUE (class_code, receipt_no ...)
     * enumerations are small code tables in `ref` (readable codes as primary keys)
     * money = numeric(16,2) in VND; signed only where a sign has business meaning
     * every transactional table keeps created_at / updated_at; legacy_ref keeps migration lineage
     * "-- comment" after a column becomes COMMENT ON COLUMN (see 04_comments.sql, generated by tools/build_comments.py)
   ===================================================================================== */

