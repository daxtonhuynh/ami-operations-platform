create domain ref.money_vnd as numeric(16,2);                                    -- Amount in VND (2 decimals kept for imported data); may be negative
create domain ref.money_vnd_pos as numeric(16,2) check (value >= 0);           -- Non-negative amount in VND
create domain ref.pct as numeric(7,4) check (value >= 0 and value <= 1);       -- Fraction between 0 and 1 (0.10 = 10%)
create domain ref.weekday as smallint check (value between 1 and 7);   -- ISO: 1 = Monday ... 7 = Sunday

/* ------------------------------------------------------------------ shared trigger function */
create or replace function ref.set_updated_at() returns trigger language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end $$;

