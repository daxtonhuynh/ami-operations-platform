-- @table Course catalogue: one row per course level of a programme.
create table ref.course (
    course_id                  smallint generated always as identity primary key,  -- Surrogate key
    course_code                text not null unique,     -- Short code used in class codes, e.g. L1 (Leaf 1), PROGRESS, A1
    programme_code             text not null references ref.programme,  -- Programme the course belongs to
    name                       text not null,            -- e.g. 'Leaf 1', 'PROGRESS 6.0+'. Legacy: 'Khoá' / 'Mã khoá học'
    audience                   text not null check (audience in ('PRIMARY','SECONDARY','HIGH_SCHOOL','ADULT','ALL')),  -- Target learner group
    level_order                smallint not null,        -- Order within the programme ladder
    entry_level_id             smallint references ref.proficiency_level,  -- Minimum entry level. Legacy: 'Trình độ đầu vào'
    exit_level_id              smallint references ref.proficiency_level,  -- Target exit level. Legacy: 'Trình độ đầu ra'
    standard_hours             numeric(6,2) not null check (standard_hours > 0),          -- Contact hours. Legacy: 'Tổng số giờ học'
    default_hours_per_session  numeric(4,2) not null check (default_hours_per_session > 0),  -- Legacy: 'Số giờ học/buổi'
    default_sessions_per_week  smallint not null check (default_sessions_per_week between 1 and 7),  -- Legacy: 'Số buổi/tuần'
    is_active                  boolean not null default true,  -- Inactive courses are not offered
    unique (programme_code, level_order)
);

-- @table Effective-dated price list per course and delivery mode (full-course or per-month price).
create table ref.course_price (
    course_price_id    integer generated always as identity primary key,   -- Surrogate key
    course_id          smallint not null references ref.course,             -- Course
    delivery_mode_code text not null references ref.delivery_mode,          -- Delivery mode
    price_basis        text not null check (price_basis in ('FULL_COURSE','PER_MONTH')),  -- Legacy: 'Học phí (Trọn gói)' / '(Theo tháng)'
    amount             ref.money_vnd_pos not null,                          -- List price in VND
    effective_from     date not null,                                       -- First day the price applies
    effective_to       date,                                                -- Day after the last valid day (NULL = open-ended)
    check (effective_to is null or effective_to > effective_from),
    exclude using gist (course_id with =, delivery_mode_code with =, price_basis with =,
                        daterange(effective_from, effective_to, '[)') with &&)
);

-- @table Effective-dated fixed fees (materials fee, standard deposit).
create table ref.fee (
    fee_id         integer generated always as identity primary key,  -- Surrogate key
    fee_code       text not null check (fee_code in ('MATERIALS','STANDARD_DEPOSIT')),  -- Fee type
    amount         ref.money_vnd_pos not null,                         -- Amount in VND. Legacy: hard-coded 200,000 / 500,000
    effective_from date not null,                                      -- First day the fee applies
    effective_to   date,                                               -- Day after the last valid day
    exclude using gist (fee_code with =, daterange(effective_from, effective_to, '[)') with &&)
);

-- @table Payment plans offered at enrolment.
create table ref.payment_plan (
    plan_code              text primary key,       -- FULL, P50_30_20, MONTHLY_3, MONTHLY_5. Legacy: 'Phương án thanh toán' + 'Gói'
    name                   text not null,          -- Display name
    materials_fee_applies  boolean not null,       -- Instalment plans add the materials fee
