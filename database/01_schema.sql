-- @table Employees (teachers, assistants, learning advisors, office staff).
create table hr.employee (
    employee_id          bigint generated always as identity primary key,  -- Surrogate key
    employee_code        text not null unique check (employee_code ~ '^E[0-9]{3,}$'),  -- Business key, e.g. E007
    full_name            text not null,             -- Full name. Legacy: 'Full Name' (payroll), employee master data
    name_code            text not null unique,      -- Given name + initials, e.g. 'Nhung NK'. Legacy: 'Name code' / 'LA phụ trách'
    gender               text check (gender in ('FEMALE','MALE','OTHER','UNDISCLOSED')),  -- Gender
    date_of_birth        date,                      -- Date of birth
    phone                text,                      -- Contact phone
    email                text,                      -- Work email
    employment_type      text not null check (employment_type in ('FULL_TIME','PART_TIME','CONTRACTOR')),  -- Drives PIT withholding rule
    home_cost_center_code text references finance.cost_center,  -- Default cost centre
    hire_date            date not null,             -- First working day
    end_date             date,                      -- Last working day (NULL = active)
    legacy_ref           text,                      -- Original identifier in the legacy files
    created_at           timestamptz not null default now(),  -- Row created
    updated_at           timestamptz not null default now(),  -- Row last updated
    check (end_date is null or end_date >= hire_date)
);
