-- @table Instalment template of each plan; the schedule generator splits the balance by share_pct.
create table ref.payment_plan_line (
    plan_code         text not null references ref.payment_plan,  -- Plan
    seq               smallint not null check (seq >= 1),          -- Instalment number
    label             text not null,                               -- e.g. '50% of tuition', 'Month 2'. Legacy: 'Ghi chú' / 'Giai đoạn'
    share_pct         ref.pct not null check (share_pct > 0),      -- Share of the balance due in this instalment
    due_offset_months smallint not null default 0 check (due_offset_months >= 0),  -- Months after the class start
    primary key (plan_code, seq)
);

-- @table Discount programmes (percentage promotions, scholarships, sales tactics).
create table ref.discount_programme (
    discount_code     text primary key,            -- e.g. OPENING_20, SALES_TACTIC_5, SCHOLARSHIP_70. Legacy: 'Chương trình giảm giá'
    name              text not null,               -- Display name
    discount_kind     text not null check (discount_kind in ('PERCENT','FIXED')),  -- Percentage of list price or fixed amount
    discount_value    numeric(16,4) not null check (discount_value > 0),  -- 0.20 for 20 %, or a VND amount
    valid_from        date not null,               -- First day the programme can be applied
    valid_to          date,                        -- Last day (inclusive); NULL = open-ended. Legacy: 'Thời gian áp dụng'
    requires_approval boolean not null default false,  -- Needs manager approval (scholarships, ad-hoc tactics)
    is_scholarship    boolean not null default false,  -- Scholarship rather than commercial discount
    check (discount_kind <> 'PERCENT' or discount_value <= 1),
    check (valid_to is null or valid_to >= valid_from)
);

-- @table Fixed discount per learner for group registrations, by group size.
create table ref.group_discount_tier (
