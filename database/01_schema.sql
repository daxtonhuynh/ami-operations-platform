-- 6. Closed periods reject postings, changes and deletions (BR-09 period integrity)
create or replace function finance.assert_period_open() returns trigger language plpgsql as $$
declare v_periods integer[]; v_closed integer;
begin
    if tg_table_name = 'payment_voucher_line' then
        v_periods := array[case when tg_op <> 'INSERT' then old.recognition_period_id end,
                           case when tg_op <> 'DELETE' then new.recognition_period_id end];
    elsif tg_table_name = 'payroll_run' then
        if tg_op = 'UPDATE' and new.period_id = old.period_id then
            return new;                                   -- approval / payment of a run is allowed after close
        end if;
        v_periods := array[case when tg_op <> 'INSERT' then old.period_id end,
                           case when tg_op <> 'DELETE' then new.period_id end];
    elsif tg_table_name = 'receipt' then
        if tg_op = 'UPDATE' and new.receipt_date = old.receipt_date and new.amount = old.amount and new.status = old.status then
            return new;                                   -- a void request on an old receipt is allowed; the void itself is not
        end if;
        v_periods := array[case when tg_op <> 'INSERT' then finance.period_of(old.receipt_date) end,
                           case when tg_op <> 'DELETE' then finance.period_of(new.receipt_date) end];
    elsif tg_table_name = 'refund' then
        v_periods := array[case when tg_op <> 'INSERT' then finance.period_of(old.refund_date) end,
                           case when tg_op <> 'DELETE' then finance.period_of(new.refund_date) end];
    elsif tg_table_name = 'write_off' then
        v_periods := array[case when tg_op <> 'INSERT' then finance.period_of(old.write_off_date) end,
                           case when tg_op <> 'DELETE' then finance.period_of(new.write_off_date) end];
    else
        v_periods := array[case when tg_op <> 'INSERT' then old.period_id end,
                           case when tg_op <> 'DELETE' then new.period_id end];
    end if;
    select min(period_id) into v_closed from finance.fiscal_period
     where period_id = any (v_periods) and status = 'CLOSED';
    if v_closed is not null then
        raise exception 'Period % is closed: % rejected', v_closed, tg_table_name;
    end if;
    return case when tg_op = 'DELETE' then old else new end;
end $$;
create trigger trg_voucher_line_period before insert or update or delete on finance.payment_voucher_line for each row execute function finance.assert_period_open();
