-- 3. Allocations may not exceed the receipt amount nor the amount due on the schedule line
create or replace function billing.check_allocation() returns trigger language plpgsql as $$
declare
    v_receipt_amount numeric; v_receipt_status text; v_allocated_receipt numeric;
    v_due numeric; v_allocated_line numeric;
begin
    select amount, status into v_receipt_amount, v_receipt_status from billing.receipt where receipt_id = new.receipt_id;
    if v_receipt_status = 'VOID' then
        raise exception 'Receipt % is void and cannot be allocated', new.receipt_id;
    end if;
    if exists (select 1 from billing.receipt r join finance.fiscal_period p on p.period_id = finance.period_of(r.receipt_date)
               where r.receipt_id = new.receipt_id and p.status = 'CLOSED') then
        raise exception 'Receipt % is dated in a closed period and cannot be allocated', new.receipt_id;
    end if;
    select coalesce(sum(amount),0) into v_allocated_receipt from billing.payment_allocation where receipt_id = new.receipt_id;
    if v_allocated_receipt > v_receipt_amount then
        raise exception 'Over-allocation: receipt % has % allocated but only % received', new.receipt_id, v_allocated_receipt, v_receipt_amount;
    end if;
    select amount_due into v_due from billing.payment_schedule where schedule_line_id = new.schedule_line_id;
    select coalesce(sum(amount),0) into v_allocated_line from billing.payment_allocation where schedule_line_id = new.schedule_line_id;
    if v_allocated_line > v_due then
        raise exception 'Over-payment: schedule line % is due % but % is allocated', new.schedule_line_id, v_due, v_allocated_line;
    end if;
    return null;
end $$;
create constraint trigger trg_check_allocation after insert or update on billing.payment_allocation
    for each row execute function billing.check_allocation();

-- 4. Journal entries must balance (checked at commit so lines can be inserted one by one)
create or replace function finance.check_journal_balanced() returns trigger language plpgsql as $$
declare v_id bigint; v_diff numeric;
begin
    v_id := coalesce(new.journal_entry_id, old.journal_entry_id);
    select coalesce(sum(debit),0) - coalesce(sum(credit),0) into v_diff from finance.journal_line where journal_entry_id = v_id;
    if v_diff <> 0 then
        raise exception 'Journal entry % is not balanced (debit - credit = %)', v_id, v_diff;
    end if;
    return null;
end $$;
create constraint trigger trg_journal_balanced after insert or update or delete on finance.journal_line
    deferrable initially deferred for each row execute function finance.check_journal_balanced();

