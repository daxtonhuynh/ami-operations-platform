-- 8. Audit trail (BR-12): who changed a financially significant row, when, and the values before / after.
--    The application sets the user name for each transaction with set_config('ami.app_user', <username>, true).
create or replace function app.audit_row() returns trigger language plpgsql security definer
set search_path = pg_catalog, pg_temp as $$
declare v_old jsonb; v_new jsonb; v_key text;
begin
    if tg_op <> 'INSERT' then v_old := to_jsonb(old) - 'password_hash'; end if;
    if tg_op <> 'DELETE' then v_new := to_jsonb(new) - 'password_hash'; end if;
    v_key := coalesce(v_new, v_old) ->> tg_argv[0];
    if tg_op = 'UPDATE' and v_old = v_new then
        return new;
    end if;
    -- Inside SECURITY DEFINER code current_user is the owner, so the application role is taken from the session setting the app
    -- writes at the start of every transaction (falls back to the login role for work done outside the app).
    insert into app.audit_log (app_user, db_role, table_name, action, row_key, old_row, new_row)
    values (nullif(current_setting('ami.app_user', true), ''),
            coalesce(nullif(current_setting('ami.app_role', true), ''), session_user::text),
            tg_table_schema || '.' || tg_table_name, tg_op, v_key, v_old, v_new);
    return case when tg_op = 'DELETE' then old else new end;
end $$;

-- 7. Teaching hours can only be logged by staff assigned to the class
create or replace function academic.check_session_staff() returns trigger language plpgsql as $$
begin
    if not exists (
        select 1 from academic.class_session s
        join academic.class_staff_assignment a on a.class_id = s.class_id and a.employee_role_id = new.employee_role_id
        where s.session_id = new.session_id
          and s.session_date >= a.effective_from
          and (a.effective_to is null or s.session_date < a.effective_to)) then
        raise exception 'Employee role % is not assigned to the class of session %', new.employee_role_id, new.session_id;
    end if;
    return new;
end $$;
create trigger trg_session_staff_assigned before insert or update on academic.session_staff
    for each row execute function academic.check_session_staff();

