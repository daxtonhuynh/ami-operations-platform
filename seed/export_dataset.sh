#!/usr/bin/env bash
# Export the generated operating data as one SQL file that loads into a database built with database/build.sql.
#   bash seed/export_dataset.sh ami_gen > seed/demo_dataset.sql
# The file truncates every table and reloads it with COPY, so it can be loaded again to reset the demo (weekly job).
# Triggers are switched off while loading (session_replication_role = replica): the data already passed every rule
# when it was generated, and the audit trail is part of the data.
set -euo pipefail
DB="${1:?usage: export_dataset.sh <database>}"
SCHEMAS=(ref crm academic billing hr payroll finance ctl app)
AS_OF=$(psql -d "$DB" -Atc "select setting_value from ref.app_setting where setting_key = 'as_of_date'")
TABLES=$(psql -d "$DB" -Atc "select string_agg(format('%I.%I', schemaname, tablename), ', ' order by schemaname, tablename)
                              from pg_tables where schemaname in ('ref','crm','academic','billing','hr','payroll','finance','ctl','app')")
cat <<HEADER
-- =====================================================================================================
-- AMI Operations - demo dataset (generated by seed/generate_dataset.py; do not edit by hand)
-- Business date: ${AS_OF}. All people, phone numbers and amounts are fictitious.
-- Load into a database built with database/build.sql:
--     psql -v ON_ERROR_STOP=1 "\$DATABASE_URL" -f seed/demo_dataset.sql
-- =====================================================================================================
SET session_replication_role = replica;
TRUNCATE ${TABLES} RESTART IDENTITY;
HEADER
pg_dump -d "$DB" --data-only --no-owner --no-privileges --no-comments $(printf -- '-n %s ' "${SCHEMAS[@]}") \
  | grep -v '^SET transaction_timeout' \
  | sed -e '/^-- Dumped from/d' -e '/^-- Dumped by/d'
cat <<'FOOTER'
SET session_replication_role = DEFAULT;
ANALYZE;
FOOTER
